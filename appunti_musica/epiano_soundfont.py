#!/usr/bin/env python3
"""Deterministic original electric piano (Rhodes-like, soft) in a small SoundFont.

No third-party audio samples: every note is synthesized with two-operator FM
(1:1 ratio, index falling after the attack), a short second-harmonic "bark" and a
very short high "tine". Program 0/bank 0, the program LilyPond writes for
"acoustic grand", so existing scores play it without changes. One sample every
six semitones from A1 to C7. Uses only the standard library and the SoundFont 2 format.
"""
from pathlib import Path
import array
import math
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]  # radice della libreria appunti-musica
RATE = 32000
ROOTS = list(range(33, 97, 6))
# Variante "morbido", scelta dall'utente il 2026-11-24 fra morbido, brillante e tremolo.
INDEX, INDEX_DECAY, TINE, BARK = 0.9, 0.35, 0.05, 0.10
RELEASE = -2400          # timecents: circa 0,25 s


def note(midi):
    f = 440 * 2 ** ((midi - 69) / 12)
    seconds = min(7.0, max(2.0, 7.0 * (110 / f) ** 0.45))
    tau = min(4.0, max(0.6, 3.2 * (110 / f) ** 0.5))
    scale_index = (220 / max(f, 220)) ** 0.3       # acuti meno ruvidi
    tine_on = f * 14 < 0.42 * RATE
    w = 2 * math.pi * f
    values = []
    for i in range(int(RATE * seconds)):
        t = i / RATE
        env = min(1, t / 0.003) * math.exp(-t / tau) * min(1, (seconds - t) / 0.3)
        index = INDEX * (0.35 + 0.65 * math.exp(-t / INDEX_DECAY)) * scale_index
        v = math.sin(w * t + index * math.sin(w * t))
        v += BARK * math.sin(2 * w * t) * math.exp(-t / 0.4)
        if tine_on:
            v += TINE * math.sin(14 * w * t) * math.exp(-t / 0.035)
        values.append(v * env)
    gain = 0.7 * (110 / f) ** -0.15 / max(abs(v) for v in values)   # acuti un po' più presenti
    out = array.array('h', (max(-32767, min(32767, round(v * gain * 32767))) for v in values))
    if sys.byteorder != 'little':
        out.byteswap()
    return out.tobytes()


def chunk(tag, data):
    return tag + struct.pack('<I', len(data)) + data + (b'\0' if len(data) % 2 else b'')


def group(kind, *chunks):
    return chunk(b'LIST', kind + b''.join(chunks))


def name(s):
    return s.encode('ascii')[:19].ljust(20, b'\0')


def text(s):
    """Stringa INFO a lunghezza pari, come richiede RIFF."""
    data = s.encode('ascii') + b'\0'
    return data + (b'\0' if len(data) % 2 else b'')


def build():
    pcm, headers, offset = b'', [], 0
    for root in ROOTS:
        data = note(root)
        size = len(data) // 2
        headers.append(struct.pack('<20sIIIIIBbHH', name(f'ep{root}'), offset, offset + size,
                                   offset + 1, offset + size - 1, RATE, root, 0, 0, 1))
        pcm += data + b'\0' * 92
        offset += size + 46
    headers.append(struct.pack('<20sIIIIIBbHH', name('EOS'), offset, offset, offset, offset, RATE, 0, 0, 0, 1))
    phdr = b''.join(struct.pack('<20sHHHIII', name(n), p, b, bag, 0, 0, 0)
                    for n, p, b, bag in [('Appunti EPiano', 0, 0, 0), ('EOP', 0, 0, 1)])
    pbag = struct.pack('<HH', 0, 0) + struct.pack('<HH', 1, 0)
    pgen = struct.pack('<HH', 41, 0) + struct.pack('<HH', 0, 0)
    inst = struct.pack('<20sH', name('EPiano'), 0) + struct.pack('<20sH', name('EOI'), len(ROOTS))
    gens, bags = [], []
    for i, root in enumerate(ROOTS):
        low = 0 if i == 0 else root - 3
        high = 127 if i == len(ROOTS) - 1 else root + 2
        bags.append(struct.pack('<HH', len(gens), 0))
        gens.append(struct.pack('<HH', 43, low + (high << 8)))     # keyRange
        gens.append(struct.pack('<Hh', 38, RELEASE))                # releaseVolEnv
        gens.append(struct.pack('<HH', 58, root))                  # overridingRootKey
        gens.append(struct.pack('<HH', 53, i))                     # sampleID
    bags.append(struct.pack('<HH', len(gens), 0))
    gens.append(struct.pack('<HH', 0, 0))
    info = group(b'INFO', chunk(b'ifil', struct.pack('<HH', 2, 1)), chunk(b'isng', text('EMU8000')),
                 chunk(b'INAM', text('Appunti original electric piano')),
                 chunk(b'ICMT', text('Original FM synthesis, no third-party samples; generated by epiano_soundfont.py')))
    sdta = group(b'sdta', chunk(b'smpl', pcm))
    pdta = group(b'pdta', chunk(b'phdr', phdr), chunk(b'pbag', pbag), chunk(b'pmod', b'\0' * 10),
                 chunk(b'pgen', pgen), chunk(b'inst', inst), chunk(b'ibag', b''.join(bags)),
                 chunk(b'imod', b'\0' * 10), chunk(b'igen', b''.join(gens)),
                 chunk(b'shdr', b''.join(headers)))
    body = b'sfbk' + info + sdta + pdta
    return b'RIFF' + struct.pack('<I', len(body)) + body


if __name__ == '__main__':
    target = ROOT / 'sf/AppuntiEPiano.sf2'
    target.write_bytes(build())
    print(target.name, target.stat().st_size, 'bytes')
